/** The scenario a query names (S10, s10, S5 for S05), or null. */
export function scenarioOf(query) {
  const m = /^s0*(\d{1,2})$/i.exec(String(query ?? '').trim());
  if (!m) return null;
  const name = `S${m[1].padStart(2, '0')}`;
  return SCENARIO_BUOYS[name] ? name : null;
}
